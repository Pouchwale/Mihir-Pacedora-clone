// Local development uses SQLite; production (Render) uses PostgreSQL.
// prisma/schema.prisma is the source of truth (PostgreSQL). This writes a SQLite copy of it
// to prisma/schema.sqlite.prisma, which run.bat uses to generate the local Prisma client.
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "prisma");
const schema = fs.readFileSync(path.join(dir, "schema.prisma"), "utf8");

const sqlite = schema.replace(/provider\s*=\s*"postgresql"/, 'provider = "sqlite"');
if (sqlite === schema) {
  console.error('Could not find provider = "postgresql" in prisma/schema.prisma');
  process.exit(1);
}

const header = "// GENERATED by scripts/make-sqlite-schema.js for local development. Do not edit.\n";
fs.writeFileSync(path.join(dir, "schema.sqlite.prisma"), header + sqlite);
console.log("Wrote prisma/schema.sqlite.prisma");
